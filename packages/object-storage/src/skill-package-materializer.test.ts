it.each(["initial", "publish"])(
	"rejects assembly-root replacement at %s without writing through the symlink",
	async (timing) => {
		const assemblyRoot = await root();
		const outside = await root();
		const original = await materializer(assemblyRoot).materialize({
			packages: [selection],
		});
		await writeFile(join(outside, "sentinel"), "unchanged");
		const moved = `${assemblyRoot}-moved`;
		roots.push(moved);
		const upgraded = await selectionFor("2.0.0");
		const adapter = new SkillPackageMaterializerV1({
			assemblyRoot,
			runtimeUid: 65534,
			readPackage: async (object: SkillPackagePublicationObjectV1) => ({
				...object,
				bytes: archive,
			}),
			verifyAdmission: async () => {
				if (
					(await readdir(join(assemblyRoot, "generations"))).length >
					(timing === "initial" ? 0 : 1)
				) {
					await rename(assemblyRoot, moved);
					await symlink(outside, assemblyRoot);
				}
			},
		});
		await expect(
			adapter.materialize({ packages: [upgraded] }),
		).rejects.toMatchObject({ code: "conflict" });
		expect(await readdir(outside)).toEqual(["sentinel"]);
		expect(await materializer(moved).readCurrent()).toEqual(original);
	},
);

