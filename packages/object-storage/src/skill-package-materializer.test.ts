const roots: string[] = [];
async function root() {
	const path = await realpath(
		await mkdtemp(join(tmpdir(), "skill-materializer-")),
	);
	roots.push(path);
	return path;
}
async function makeWritable(path: string): Promise<void> {
	await chmod(path, 0o700);
	for (const entry of await readdir(path, { withFileTypes: true }))
		if (entry.isDirectory()) await makeWritable(join(path, entry.name));
}
afterEach(async () => {
	for (const path of roots.splice(0)) {
		if ((await lstat(path)).isSymbolicLink()) {
			await rm(path);
			continue;
		}
		await makeWritable(path);
		await rm(path, { recursive: true, force: true });
	}
});
function materializer(assemblyRoot: string) {
	return new SkillPackageMaterializerV1({
		assemblyRoot,
		runtimeUid: 65534,
		readPackage: async (object: SkillPackagePublicationObjectV1) => ({
			...object,
			bytes: archive,
		}),
		verifyAdmission: async () => {},
	});
}
function project(assemblyRoot: string, generationId: string) {
	return join(assemblyRoot, "generations", generationId);
}

describe("Skill package materializer", () => {
	it("publishes one complete immutable generation and retains fixed object references", async () => {
		const assemblyRoot = await root();
		const adapter = materializer(assemblyRoot);
		const result = await adapter.materialize({ packages: [selection] });
		expect(result).toMatchObject({
			schemaVersion: 1,
			status: "materialized",
			packages: [selection],
		});
		expect(result).not.toHaveProperty("readOnly");
		expect(result).not.toHaveProperty("available");
		expect(await adapter.readCurrent()).toEqual(result);
		const directory = project(assemblyRoot, result.generationId);
		expect(
			await readFile(
				join(directory, ".agents/skills/workspace-summary/SKILL.md"),
				"utf8",
			),
		).toBe("# Summary\n");
		expect(
			await readFile(join(directory, ".agents/SKILLS.md"), "utf8"),
		).toContain("workspace-summary@1.0.0");
		expect(
			(await stat(join(directory, ".agents/skills/workspace-summary/SKILL.md")))
				.mode & 0o777,
		).toBe(0o444);
		expect((await stat(directory)).mode & 0o777).toBe(0o555);
	});
});

