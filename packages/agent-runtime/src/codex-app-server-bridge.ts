function isPlainRecord(value: unknown): value is Record<string, unknown> {
	return (
		typeof value === "object" &&
		value !== null &&
		!Array.isArray(value) &&
		Object.getPrototypeOf(value) === Object.prototype
	);
}

function exactKeys(value: Record<string, unknown>, keys: readonly string[]) {
	return (
		Object.keys(value).length === keys.length &&
		Object.keys(value).every((key) => keys.includes(key))
	);
}

function hasPinnedProvenance(
	value: unknown,
): value is CodexAppServerProvenanceV2 {
	if (
		!isPlainRecord(value) ||
		!exactKeys(value, [
			"protocolVersion",
			"codexVersion",
			"upstreamTag",
			"upstreamCommit",
			"schemaSha256",
		]) ||
		value.protocolVersion !== 2 ||
		typeof value.codexVersion !== "string" ||
		typeof value.upstreamTag !== "string" ||
		typeof value.upstreamCommit !== "string" ||
		typeof value.schemaSha256 !== "string" ||
		!sha256Pattern.test(value.schemaSha256)
	) {
		return false;
	}
	return (
		value.codexVersion === CODEX_APP_SERVER_V2_PROVENANCE.codexVersion &&
		value.upstreamTag === CODEX_APP_SERVER_V2_PROVENANCE.upstreamTag &&
		value.upstreamCommit === CODEX_APP_SERVER_V2_PROVENANCE.upstreamCommit &&
		value.schemaSha256 === CODEX_APP_SERVER_V2_PROVENANCE.schemaSha256
	);
}

function parseTimeout(value: unknown, fallback: number) {
	if (value === undefined) return fallback;
	if (
		typeof value !== "number" ||
		!Number.isSafeInteger(value) ||
		value < minimumTimeoutMs ||
		value > maximumTimeoutMs
	) {
		configurationInvalid();
	}
	return value;
}

function validateOptions(input: unknown): ValidatedOptions {
	if (!isPlainRecord(input)) configurationInvalid();
	const allowedKeys = [
		"launchPath",
		"dataDirectory",
		"conversationKey",
		"model",
		"reasoningEffort",
		"modelAccess",
		"provenance",
		"startupTimeoutMs",
		"shutdownTimeoutMs",
	];
	if (!Object.keys(input).every((key) => allowedKeys.includes(key))) {
		configurationInvalid();
	}
	if (
		typeof input.dataDirectory !== "string" ||
		!isAbsolute(input.dataDirectory) ||
		dirname(input.dataDirectory) === input.dataDirectory ||
		resolve(input.dataDirectory) !== input.dataDirectory ||
		[...input.dataDirectory].some(
			(character) => character.charCodeAt(0) < 32,
		) ||
		typeof input.conversationKey !== "string" ||
		!conversationKeyPattern.test(input.conversationKey) ||
		typeof input.model !== "string" ||
		(!realModelPattern.test(input.model) &&
			!namespacedModelPattern.test(input.model)) ||
		typeof input.reasoningEffort !== "string" ||
		!reasoningEffortPattern.test(input.reasoningEffort)
	) {
		configurationInvalid();
	}
	if (
		input.launchPath !== undefined &&
		(typeof input.launchPath !== "string" ||
			!input.launchPath ||
			[...input.launchPath].some(
				(character) =>
					character.charCodeAt(0) < 32 || character.charCodeAt(0) === 127,
			) ||
			input.launchPath
				.split(delimiter)
				.some((entry) => !entry || !isAbsolute(entry)))
	)
		configurationInvalid();
	if (!hasPinnedProvenance(input.provenance)) provenanceMismatch();
	const modelAccess = validateModelAccess(input.modelAccess);
	if (modelAccess && !namespacedModelPattern.test(input.model)) {
		configurationInvalid();
	}
	return {
		...(input.launchPath !== undefined ? { launchPath: input.launchPath } : {}),
		dataDirectory: input.dataDirectory,
		conversationKey: input.conversationKey,
		model: input.model,
		reasoningEffort: input.reasoningEffort,
		...(modelAccess ? { modelAccess } : {}),
		startupTimeoutMs: parseTimeout(input.startupTimeoutMs, defaultTimeoutMs),
		shutdownTimeoutMs: parseTimeout(input.shutdownTimeoutMs, defaultTimeoutMs),
	};
}

export function validateModelAccess(
	input: unknown,
): CodexModelAccess | undefined {
	if (input === undefined) return undefined;
	if (
		!isPlainRecord(input) ||
		!exactKeys(input, ["endpoint", "credential"]) ||
		typeof input.endpoint !== "string" ||
		input.endpoint.length > 2048 ||
		/[\s\\?#]/.test(input.endpoint) ||
		typeof input.credential !== "string" ||
		!/^[\x21-\x7e]{16,8192}$/.test(input.credential)
	) {
		configurationInvalid();
	}
	try {
		const endpoint = new URL(input.endpoint);
		// Match the literal authority, not URL-normalized numeric host aliases.
		const literalLoopback =
			/^http:\/\/(?:127\.0\.0\.1|\[::1\])(?::[0-9]+)?(?:\/|$)/.test(
				input.endpoint,
			);
		if (
			(endpoint.protocol !== "https:" && !literalLoopback) ||
			endpoint.username ||
			endpoint.password ||
			endpoint.search ||
			endpoint.hash
		) {
			configurationInvalid();
		}
	} catch {
		configurationInvalid();
	}
	return { endpoint: input.endpoint, credential: input.credential };
}

