function kill(
	process: Pick<ChildProcess, "kill">,
	signal: "SIGTERM" | "SIGKILL" = "SIGTERM",
) {
	try {
		process.kill(signal);
	} catch {
		// The process already exited.
	}
}

async function waitForResult<T>(promise: Promise<T>, timeoutMs: number) {
	let timer: ReturnType<typeof setTimeout> | undefined;
	try {
		return await Promise.race([
			promise,
			new Promise<undefined>((resolve) => {
				timer = setTimeout(() => resolve(undefined), timeoutMs);
			}),
		]);
	} finally {
		if (timer) clearTimeout(timer);
	}
}

async function reapChild(
	process: Pick<ChildProcess, "kill">,
	closed: Promise<true>,
	timeoutMs: number,
) {
	kill(process);
	if (await waitForResult(closed, timeoutMs)) return;
	kill(process, "SIGKILL");
	await waitForResult(closed, timeoutMs);
}

async function resolveExecutable(path: string | undefined, name: string) {
	if (!path) throw unavailable();
	for (const directory of path.split(delimiter)) {
		if (!directory) continue;
		const candidate = join(directory, name);
		try {
			await access(candidate, constants.X_OK);
			return await realpath(candidate);
		} catch {
			// Continue searching only PATH entries.
		}
	}
	throw unavailable();
}

async function createIsolatedLaunchPolicy(
	path: string | undefined,
): Promise<IsolatedLaunchPolicy> {
	if (!path) throw unavailable();
	try {
		const directory = await mkdtemp(
			join(tmpdir(), isolatedRuntimeDirectoryPrefix),
		);
		const environment: NodeJS.ProcessEnv = {
			CODEX_HOME: directory,
			HOME: directory,
			PATH: path,
		};
		if (process.platform === "darwin") {
			environment.__CF_USER_TEXT_ENCODING =
				process.env.__CF_USER_TEXT_ENCODING ?? "";
		}
		return {
			directory,
			environment,
		};
	} catch {
		throw unavailable();
	}
}

async function removeIsolatedDirectory(directory: string) {
	try {
		await rm(directory, { recursive: true, force: true });
	} catch {
		// Only the ephemeral HOME/probe/scratch directory is eligible for cleanup.
	}
}

interface ConversationLaunchPolicy extends IsolatedLaunchPolicy {
	// Native filesystem boundary the enforced policy excludes.
	boundary: string;
	root: string;
	home: string;
}

async function ensureOwnedDirectory(directory: string, create: boolean) {
	if (create) {
		await mkdir(directory, { mode: 0o700 }).catch(
			(error: NodeJS.ErrnoException) => {
				if (error.code !== "EEXIST") throw error;
			},
		);
	}
	const metadata = await lstat(directory);
	if (
		!metadata.isDirectory() ||
		(process.getuid &&
			(metadata.uid !== process.getuid() || (metadata.mode & 0o077) !== 0))
	)
		configurationInvalid();
}

async function persistentLaunchPolicy(
	dataDirectory: string,
	conversationKey: string,
	isolated: IsolatedLaunchPolicy,
): Promise<ConversationLaunchPolicy> {
	try {
		// Resolve the deployment parent (for example a mounted PVC), never follow a
		// symlink at the data root or any native data directory.
		const parent = await realpath(dirname(dataDirectory));
		const dataRoot = join(parent, basename(dataDirectory));
		for (const personal of [
			process.env.HOME,
			process.env.CODEX_HOME,
			process.cwd(),
		]) {
			if (!personal) continue;
			const canonical = await realpath(personal).catch(() => resolve(personal));
			const personalPrefix = canonical.endsWith(sep)
				? canonical
				: `${canonical}${sep}`;
			if (
				canonical === dataRoot ||
				canonical.startsWith(`${dataRoot}${sep}`) ||
				dataRoot.startsWith(personalPrefix)
			)
				configurationInvalid();
		}
		// One directory per Conversation generation beneath a shared boundary. The
		// key is server-derived, so siblings can never be named by a wire field.
		const boundary = join(dataRoot, conversationBoundaryDirectory);
		const root = join(boundary, conversationKey);
		const home = join(root, "home");
		const workspace = join(root, "workspace");
		await ensureOwnedDirectory(dataRoot, true);
		await ensureOwnedDirectory(boundary, true);
		// A Conversation that already owns storage never has a lost directory
		// recreated; its native operations and replay fail closed instead.
		const existing = await lstat(root).catch((error: NodeJS.ErrnoException) => {
			if (error.code === "ENOENT") return undefined;
			throw error;
		});
		for (const directory of [root, home, workspace]) {
			await ensureOwnedDirectory(directory, !existing);
		}
		// Durable native state is not a source of credentials or configuration.
		for (const file of [
			join(home, "config.toml"),
			join(home, "managed_config.toml"),
			join(home, "auth.json"),
			join(workspace, ".codex"),
		]) {
			const found = await lstat(file).catch((error: NodeJS.ErrnoException) => {
				if (error.code === "ENOENT") return undefined;
				throw error;
			});
			if (found) configurationInvalid();
		}
		return {
			directory: workspace,
			boundary,
			root,
			home,
			environment: {
				...isolated.environment,
				CODEX_HOME: home,
				TMPDIR: isolated.directory,
			},
		};
	} catch (error) {
		if (error instanceof CodexAppServerBridgeError) throw error;
		throw unavailable();
	}
}

/**
 * Darwin cannot wrap the native process in a further restricted Seatbelt
 * profile: pinned Codex runs its own tools through `sandbox-exec`, and any
 * enforcing outer profile makes the nested `sandbox_apply` fail, which would
 * disable every tool instead of isolating Conversations. Pinned Codex therefore
 * enforces this profile itself. Denying the shared boundary keeps every other
 * Conversation's native workspace and history unreadable, while the owning
 * Conversation keeps a writable workspace and a read-only native home, so model
 * tools cannot write native configuration, skills, or history.
 */
function conversationPermissionArguments(policy: ConversationLaunchPolicy) {
	const filesystem = [
		[policy.boundary, "deny"],
		[policy.home, "read"],
		[policy.directory, "write"],
	]
		.map(
			([path, access]) => `${JSON.stringify(path)}=${JSON.stringify(access)}`,
		)
		.join(",");
	return [
		"--config",
		`permissions={${conversationPermissionProfileId}={extends=":workspace",filesystem={${filesystem}}}}`,
		"--config",
		`default_permissions=${JSON.stringify(conversationPermissionProfileId)}`,
	];
}

async function existingDirectory(path: string) {
	const metadata = await lstat(path).catch(() => undefined);
	return metadata?.isDirectory() === true;
}

/**
 * Linux keeps the pinned legacy Landlock backend, which refuses a permission
 * profile requiring direct runtime enforcement. The deployment's trusted
 * `setpriv` therefore applies the boundary to the whole native process instead.
 * Landlock rules only ever add access, so an allowlist is the only way to
 * exclude a sibling Conversation; Landlock rulesets stack, so pinned Codex still
 * applies its own policy to tool children beneath this one.
 */
async function conversationLandlockArguments(
	executable: string,
	launchPath: string | undefined,
	policy: ConversationLaunchPolicy,
) {
	const rules: string[] = [];
	const allow = async (rights: string, path: string) => {
		if (!(await existingDirectory(path))) return;
		rules.push("--landlock-rule", `path-beneath:${rights}:${path}`);
	};
	// The pinned release and its bundled resources stay read-only.
	await allow(landlockProgramRights, dirname(dirname(executable)));
	for (const entry of (launchPath ?? "").split(delimiter)) {
		if (entry) await allow(landlockProgramRights, entry);
	}
	for (const path of ["/bin", "/sbin", "/usr", "/lib", "/lib64"]) {
		await allow(landlockProgramRights, path);
	}
	for (const path of ["/etc", "/proc", "/sys"]) {
		await allow(landlockMetadataRights, path);
	}
	await allow(landlockDataRights, "/dev");
	// Only this Conversation's durable directory and the ephemeral HOME/TMPDIR.
	const ephemeral = policy.environment.TMPDIR;
	if (ephemeral) await allow(landlockDataRights, ephemeral);
	await allow(landlockDataRights, policy.root);
	if (!rules.includes(`path-beneath:${landlockDataRights}:${policy.root}`)) {
		throw unavailable();
	}
	return [
		"--no-new-privs",
		"--landlock-access",
		`fs:${landlockDataRights}`,
		...rules,
	];
}

/**
 * The platform never routes a native process's loopback traffic through a
 * proxy: the active model endpoint is always loopback, and a host proxy
 * configuration must not intercept it. The launch environment carries no proxy
 * variables of its own, so this only refuses an operating-system proxy.
 */
function loopbackProxyEnvironment() {
	return {
		NO_PROXY: loopbackProxyExclusions,
		no_proxy: loopbackProxyExclusions,
	};
}

interface CommandOutput {
	stdout: string;
	stdoutTooLarge: boolean;
}

type CommandOutcome =
	| { kind: "close"; code: number | null }
	| { kind: "error" };

async function runProbeCommand(
	executable: string,
	args: readonly string[],
	timeoutMs: number,
	captureStdout: boolean,
	launchPolicy: IsolatedLaunchPolicy,
): Promise<CommandOutput> {
	let process: ChildProcess;
	try {
		process = spawn(executable, args, {
			stdio: ["ignore", captureStdout ? "pipe" : "ignore", "ignore"],
			cwd: launchPolicy.directory,
			env: launchPolicy.environment,
		});
	} catch {
		throw unavailable();
	}
	const closed = new Promise<true>((resolve) => {
		process.once("close", () => resolve(true));
	});
	const outcome = new Promise<CommandOutcome>((resolve) => {
		process.once("error", () => resolve({ kind: "error" }));
		process.once("close", (code) => resolve({ kind: "close", code }));
	});
	let stdout = "";
	let stdoutBytes = 0;
	let stdoutTooLarge = false;
	if (captureStdout) {
		if (!process.stdout) {
			await reapChild(process, closed, timeoutMs);
			throw unavailable();
		}
		process.stdout.on("data", (chunk: Buffer) => {
			if (stdoutTooLarge) return;
			if (chunk.byteLength > maximumFrameBytes - stdoutBytes) {
				stdoutTooLarge = true;
				return;
			}
			stdoutBytes += chunk.byteLength;
			stdout += chunk.toString("utf8");
		});
	}
	const result = await waitForResult(outcome, timeoutMs);
	if (!result) {
		await reapChild(process, closed, timeoutMs);
		throw timedOut();
	}
	if (result.kind === "error" || result.code !== 0) {
		await reapChild(process, closed, timeoutMs);
		throw unavailable();
	}
	return { stdout, stdoutTooLarge };
}

async function probeVersion(
	executable: string,
	timeoutMs: number,
	launchPolicy: IsolatedLaunchPolicy,
) {
	const output = await runProbeCommand(
		executable,
		["--version"],
		timeoutMs,
		true,
		launchPolicy,
	);
	if (
		output.stdoutTooLarge ||
		output.stdout.trim() !==
			`codex-cli ${CODEX_APP_SERVER_V2_PROVENANCE.codexVersion}`
	) {
		throw provenanceMismatchError();
	}
}

async function verifySchema(
	executable: string,
	timeoutMs: number,
	launchPolicy: IsolatedLaunchPolicy,
) {
	let directory: string;
	try {
		directory = await mkdtemp(join(tmpdir(), "agent-runtime-codex-schema-"));
	} catch {
		throw unavailable();
	}
	let failure: CodexAppServerBridgeError | undefined;
	try {
		await runProbeCommand(
			executable,
			["app-server", "generate-json-schema", "--out", directory],
			timeoutMs,
			false,
			launchPolicy,
		);
		const schema = await readFile(join(directory, schemaArtifactName));
		const digest = `sha256:${createHash("sha256").update(schema).digest("hex")}`;
		if (digest !== CODEX_APP_SERVER_V2_PROVENANCE.schemaSha256) {
			failure = provenanceMismatchError();
		}
	} catch (error) {
		failure =
			error instanceof CodexAppServerBridgeError
				? error
				: provenanceMismatchError();
	}
	try {
		await rm(directory, { recursive: true, force: true });
	} catch {
		failure ??= unavailable();
	}
	if (failure) throw failure;
}

async function verifyLinuxSandbox(
	launchPolicy: IsolatedLaunchPolicy,
	timeoutMs: number,
) {
	if (platform !== "linux") return;
	try {
		const helper = await resolveExecutable(
			launchPolicy.environment.PATH,
			"setpriv",
		);
		// ABI V5's newest filesystem right must install without BestEffort masking.
		// setpriv fails if the kernel or container policy cannot enforce the rule.
		await runProbeCommand(
			helper,
			[
				"--no-new-privs",
				"--landlock-access",
				"fs:ioctl-dev",
				"--",
				"/bin/true",
			],
			timeoutMs,
			false,
			launchPolicy,
		);
	} catch {
		throw new CodexAppServerBridgeError(
			"CODEX_APP_SERVER_SANDBOX_UNAVAILABLE",
			"Codex requires setpriv and enforceable Landlock ABI V5 filesystem rights",
		);
	}
}

function provenanceMismatchError() {
	return new CodexAppServerBridgeError(
		"CODEX_APP_SERVER_PROVENANCE_MISMATCH",
		"Codex app-server provenance does not match the pinned release",
	);
}

export class CodexAppServerBridge {
	#queue = new FrameQueue();
	#exit: Promise<void>;
	#resolveExit!: () => void;
	#output = Buffer.alloc(0);
	#failure?: CodexAppServerBridgeError;
	#closing = false;
	#isClosed = false;
	#reaping?: Promise<void>;
	#cleaning?: Promise<void>;
	#process: ChildProcessWithoutNullStreams;
	#shutdownTimeoutMs: number;

	private constructor(
		process: ChildProcessWithoutNullStreams,
		shutdownTimeoutMs: number,
		private readonly isolatedDirectory: string,
	) {
		this.#process = process;
		this.#shutdownTimeoutMs = shutdownTimeoutMs;
		this.#exit = new Promise((resolve) => {
			this.#resolveExit = resolve;
		});
		process.stderr.resume();
		process.stdout.on("data", (chunk: Buffer) => this.receive(chunk));
		process.stdin.on("error", () => this.fail(exited()));
		process.once("error", () => this.fail(unavailable()));
		process.once("close", () => {
			this.#isClosed = true;
			this.#resolveExit();
			if (this.#closing) this.#queue.finish();
			else this.fail(exited());
			void this.cleanIsolatedDirectory();
		});
	}

	static async open(options: CodexAppServerBridgeOptions) {
		const validated = validateOptions(options);
		const launchPath = validated.launchPath ?? env.PATH;
		const executable = await resolveExecutable(launchPath, "codex");
		const launchPolicy = await createIsolatedLaunchPolicy(launchPath);
		let nativeLaunchPolicy: ConversationLaunchPolicy;
		let boundary: string[];
		try {
			await probeVersion(executable, validated.startupTimeoutMs, launchPolicy);
			await verifySchema(executable, validated.startupTimeoutMs, launchPolicy);
			await verifyLinuxSandbox(launchPolicy, validated.startupTimeoutMs);
			nativeLaunchPolicy = await persistentLaunchPolicy(
				validated.dataDirectory,
				validated.conversationKey,
				launchPolicy,
			);
			// A platform without an enforceable Conversation boundary never starts a
			// native process; there is no unrestricted fallback.
			if (platform === "linux") {
				const helper = await resolveExecutable(launchPath, "setpriv");
				boundary = [
					helper,
					...(await conversationLandlockArguments(
						executable,
						launchPath,
						nativeLaunchPolicy,
					)),
					"--",
				];
			} else if (platform === "darwin") {
				boundary = [];
			} else {
				throw new CodexAppServerBridgeError(
					"CODEX_APP_SERVER_SANDBOX_UNAVAILABLE",
					"Codex requires an enforceable Conversation filesystem boundary",
				);
			}
		} catch (error) {
			await removeIsolatedDirectory(launchPolicy.directory);
			throw error;
		}
		const [command = executable, ...boundaryArguments] = boundary;
		let process: ChildProcessWithoutNullStreams;
		try {
			process = spawn(
				command,
				[
					...boundaryArguments,
					...(boundary.length > 0 ? [executable] : []),
					"app-server",
					"--stdio",
					"--strict-config",
					"--config",
					`model=${JSON.stringify(validated.model)}`,
					"--config",
					`model_reasoning_effort=${JSON.stringify(validated.reasoningEffort)}`,
					"--config",
					"mcp_servers={}",
					"--config",
					"features.plugins=false",
					// The owning Conversation keeps a writable workspace on every
					// platform; the boundary above keeps siblings unreachable. Pinned
					// Codex refuses sandbox_mode beside a permissions profile, so each
					// platform states it once.
					...(platform === "linux"
						? [
								"--config",
								'sandbox_mode="workspace-write"',
								// Landlock enforces the native policy without namespace
								// privileges. Admission above requires the full pinned
								// filesystem capability set.
								"--config",
								"features.use_legacy_landlock=true",
							]
						: conversationPermissionArguments(nativeLaunchPolicy)),
					...modelAccessArguments(validated.modelAccess),
				],
				{
					stdio: ["pipe", "pipe", "pipe"],
					cwd: nativeLaunchPolicy.directory,
					env: {
						...nativeLaunchPolicy.environment,
						...loopbackProxyEnvironment(),
						...(validated.modelAccess
							? {
									[modelCredentialEnvironmentKey]:
										validated.modelAccess.credential,
								}
							: {}),
					},
				},
			);
		} catch {
			await removeIsolatedDirectory(launchPolicy.directory);
			throw unavailable();
		}
		const bridge = new CodexAppServerBridge(
			process,
			validated.shutdownTimeoutMs,
			launchPolicy.directory,
		);
		try {
			await bridge.waitForSpawn(validated.startupTimeoutMs);
			return bridge;
		} catch (error) {
			await bridge.close().catch(() => {});
			throw error;
		}
	}

	provenance(): CodexAppServerProvenanceV2 {
		return CODEX_APP_SERVER_V2_PROVENANCE;
	}

	frames(): AsyncIterable<CodexAppServerFrame> {
		return {
			[Symbol.asyncIterator]: () => ({ next: () => this.#queue.next() }),
		};
	}

	async send(frame: CodexAppServerFrame) {
		if (this.#closing || this.#isClosed || this.#failure) throw closed();
		if (!isPlainRecord(frame)) throw invalidFrame();
		let encoded: string;
		try {
			const payload = JSON.stringify(frame);
			if (payload === undefined || !isPlainRecord(JSON.parse(payload))) {
				throw invalidFrame();
			}
			encoded = `${payload}\n`;
		} catch {
			throw invalidFrame();
		}
		if (Buffer.byteLength(encoded) > maximumFrameBytes) throw invalidFrame();
		await new Promise<void>((resolve, reject) => {
			let settled = false;
			const rejectExited = () => {
				const error = exited();
				this.fail(error);
				reject(error);
			};
			const settle = (work: () => void) => {
				if (settled) return;
				settled = true;
				this.#process.stdin.off("error", onWriteError);
				work();
			};
			const onWriteError = () => settle(rejectExited);
			this.#process.stdin.once("error", onWriteError);
			try {
				this.#process.stdin.write(encoded, (error) => {
					if (error) settle(rejectExited);
					else settle(resolve);
				});
			} catch {
				settle(rejectExited);
			}
		});
	}

	async close() {
		if (this.#isClosed) {
			await this.cleanIsolatedDirectory();
			return;
		}
		if (this.#reaping) {
			await this.#reaping;
			await this.cleanIsolatedDirectory();
			return;
		}
		if (this.#closing) {
			await this.#exit;
			await this.cleanIsolatedDirectory();
			return;
		}
		this.#closing = true;
		try {
			this.#process.stdin.end();
		} catch {
			kill(this.#process);
		}
		try {
			await this.waitForExit(this.#shutdownTimeoutMs);
		} catch {
			await this.reapOwnedChild();
			throw timedOut();
		} finally {
			await this.cleanIsolatedDirectory();
		}
	}

	private async waitForSpawn(timeoutMs: number) {
		if (this.#isClosed || this.#failure) throw this.#failure ?? exited();
		await new Promise<void>((resolve, reject) => {
			let settled = false;
			const settle = (work: () => void) => {
				if (settled) return;
				settled = true;
				clearTimeout(timer);
				work();
			};
			const timer = setTimeout(() => {
				void this.reapOwnedChild().then(() => settle(() => reject(timedOut())));
			}, timeoutMs);
			this.#process.once("spawn", () => settle(resolve));
			this.#process.once("error", () => settle(() => reject(unavailable())));
			this.#process.once("close", () => settle(() => reject(exited())));
		});
	}

	private async waitForExit(timeoutMs: number) {
		let timer: ReturnType<typeof setTimeout> | undefined;
		try {
			await Promise.race([
				this.#exit,
				new Promise<never>((_, reject) => {
					timer = setTimeout(() => reject(timedOut()), timeoutMs);
				}),
			]);
		} finally {
			if (timer) clearTimeout(timer);
		}
	}

	private receive(chunk: Buffer) {
		if (this.#failure || this.#isClosed) return;
		let remaining = chunk;
		while (remaining.byteLength > 0) {
			const newline = remaining.indexOf(0x0a);
			if (newline === -1) {
				if (
					remaining.byteLength >
					maximumFrameBytes - this.#output.byteLength
				) {
					this.fail(invalidFrame());
					return;
				}
				this.#output = Buffer.concat([this.#output, remaining]);
				return;
			}
			const line = remaining.subarray(0, newline);
			remaining = remaining.subarray(newline + 1);
			if (line.byteLength > maximumFrameBytes - this.#output.byteLength) {
				this.fail(invalidFrame());
				return;
			}
			const frame =
				this.#output.byteLength === 0
					? line
					: Buffer.concat([this.#output, line]);
			this.#output = Buffer.alloc(0);
			if (frame.byteLength > maximumFrameBytes) {
				this.fail(invalidFrame());
				return;
			}
			const json = frame.at(-1) === 0x0d ? frame.subarray(0, -1) : frame;
			try {
				const value = JSON.parse(utf8.decode(json)) as unknown;
				if (!isPlainRecord(value) || !this.#queue.push(value)) {
					this.fail(invalidFrame());
					return;
				}
			} catch {
				this.fail(invalidFrame());
				return;
			}
		}
	}

	private fail(error: CodexAppServerBridgeError) {
		if (this.#failure) return;
		this.#failure = error;
		this.#queue.fail(error);
		void this.reapOwnedChild();
	}

	private async reapOwnedChild() {
		if (this.#isClosed) return;
		if (this.#reaping) return this.#reaping;
		this.#closing = true;
		this.#reaping = (async () => {
			kill(this.#process);
			try {
				await this.waitForExit(this.#shutdownTimeoutMs);
				return;
			} catch {
				kill(this.#process, "SIGKILL");
				try {
					await this.waitForExit(this.#shutdownTimeoutMs);
				} catch {
					// The process could not be reaped within the bounded cleanup window.
				}
			}
		})();
		return this.#reaping;
	}

	private cleanIsolatedDirectory() {
		if (!this.#isClosed) return Promise.resolve();
		this.#cleaning ??= removeIsolatedDirectory(this.isolatedDirectory);
		return this.#cleaning;
	}
}
